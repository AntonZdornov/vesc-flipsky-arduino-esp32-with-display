#pragma once

#include <Arduino.h>

// Ограничение скорости через лимит оборотов в конфиге VESC.
//
// Почему не setRPM: приложение газа (ADC/PPM) внутри VESC переписывает setpoint
// каждый управляющий цикл (~1 кГц), поэтому редкие COMM_SET_RPM по UART оно просто
// затирает — лимит не работает. Здесь вместо этого правится сам конфиг мотора
// (l_min_erpm / l_max_erpm) пакетом COMM_SET_MCCONF_TEMP: контроллер сам режет ток
// у порога, и газ уже физически не может его превысить.
//
// store = 0 — во флеш не пишем, значения живут до перезагрузки VESC (и мы их
// периодически повторяем из loop(), чтобы лимит переживал ребут контроллера).
void vesc_set_erpm_limit(Stream &port, float min_erpm, float max_erpm);
